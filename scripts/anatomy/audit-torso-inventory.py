def sha(data):
    return hashlib.sha256(data).hexdigest()


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--fetch', action='store_true')
args = parser.parse_args()
raw = {}
if args.fetch:
    CACHE.mkdir(parents=True, exist_ok=True)
    for name, expected in TABLES.items():
        with urllib.request.urlopen(BASE + name, timeout=60) as response:
            data = response.read()
        assert sha(data) == expected, 'Metadata changed: ' + name
        (CACHE / name).write_bytes(data)
    request = urllib.request.Request(ARCHIVE_URL, headers={
        'Range': f'bytes={CD_OFFSET}-{CD_OFFSET + CD_BYTES - 1}', 'Accept-Encoding': 'identity'})
    with urllib.request.urlopen(request, timeout=60) as response:
        assert response.status == 206
        assert response.headers.get('Content-Range') == f'bytes {CD_OFFSET}-{CD_OFFSET + CD_BYTES - 1}/{ARCHIVE_BYTES}'
        data = response.read(CD_BYTES + 1)
    assert len(data) == CD_BYTES and sha(data) == CD_SHA
    (CACHE / CD_NAME).write_bytes(data)
if SOURCE.exists() and not args.fetch:
    with zipfile.ZipFile(SOURCE) as archive:
        assert set(archive.namelist()) == set(TABLES) | {CD_NAME}
        raw = {name: archive.read(name) for name in archive.namelist()}
else:
    raw = {name: (CACHE / name).read_bytes() for name in [*TABLES, CD_NAME]}
for name, expected in {**TABLES, CD_NAME: CD_SHA}.items():
    assert sha(raw[name]) == expected, 'Pinned source mismatch: ' + name
prior_audit = json.loads((ROOT / 'docs/phase3/research/source-audit.json').read_text())
for record in prior_audit['metadata_audit']['metadata']:
    assert TABLES[record['filename']] == record['sha256']
    assert len(raw[record['filename']]) == record['bytes']
SOURCE.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(SOURCE, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for name, data in sorted(raw.items()):
        info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o100644 << 16
        archive.writestr(info, data, compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)

tables = {name: list(csv.DictReader(io.StringIO(raw[name].decode()), delimiter='\t')) for name in TABLES}
parts = {r['concept id']: r for r in tables['isa_parts_list_e.txt']}
edges = tables['isa_inclusion_relation_list.txt']
parents = {r['child id']: r for r in edges}
nonterminal = {r['parent id'] for r in edges}
bindings = collections.defaultdict(list)
for row in tables['isa_element_parts.txt']:
    bindings[row['concept id']].append(row['element file id'])
directory, offset = {}, 0
while offset < len(raw[CD_NAME]):
    header = struct.unpack_from('<4s6H3L5H2L', raw[CD_NAME], offset)
    assert header[0] == b'PK\x01\x02'
    path = raw[CD_NAME][offset + 46:offset + 46 + header[10]].decode()
    directory[Path(path).stem] = dict(path=path, bytes=header[9], compressedBytes=header[8],
        crc32=f'{header[7]:08x}', offset=header[16], method=header[4])
    offset += 46 + header[10] + header[11] + header[12]
assert len(directory) == 2234


def ancestry(cid):
    result = []
    while cid in parents:
        edge = parents[cid]
        result.append({'id': edge['parent id'], 'name': edge['parent name']})
        cid = edge['parent id']
    return result


def isa_type(cid):
    ids = {r['id'] for r in ancestry(cid)} | {cid}
    for key, value in [('FMA85453', 'head of muscle organ'), ('FMA10474', 'zone of muscle organ'),
                       ('FMA5022', 'muscle organ'), ('FMA55268', 'organ zone')]:
        if key in ids:
            return value
    return 'set/group or other anatomical entity'


def side_from_name(name):
    if 'right' in name:
        return 'right'
    if 'left' in name:
        return 'left'
    return 'unspecified'


approved = []
for family, label, region, component, right_id, left_id, fj in PAIRS:
    for side, cid, fid in [('right', right_id, fj), ('left', left_id, fj + 'M')]:
        row = parts[cid]
        assert bindings[cid] == [fid], (cid, bindings[cid])
        assert side_from_name(row['en']) == side
        assert fid in directory
        typ = isa_type(cid)
        parent = f'med3d:muscle:{family}:{side}' if component else f'muscular:region:{region}'
        if not component and family in {'iliocostalislumborum', 'iliocostalisthoracis', 'longissimusthoracis', 'spinalisthoracis'}:
            parent = 'muscular:group:back:erectors'
        elif not component and family in {'rhomboidmajor', 'rhomboidminor', 'teresmajor'}:
            parent = 'muscular:group:back:scapular'
        approved.append(dict(elementId=fid, sourceId=cid, representationId=row['representation id'],
            en=row['en'], name=label + (', ' + PART_LABELS[component] if component else ''),
            side=side, family=family, component=component,
            sourceType='muscle' if not component else ('head' if typ == 'head of muscle organ' else 'portion'),
            isaType=typ, isaAncestry=ancestry(cid), proposedParentId=parent,
            structureId=f'med3d:muscle:{family}:{side}' if component else 'bp3d:' + cid,
            regionId=f'muscular:region:{region}', moduleId='muscular:' + region,
            moduleFile=MODULE_FILES[region], archiveEntry=directory[fid],
            originalHeaderNotYetInspected=True))
