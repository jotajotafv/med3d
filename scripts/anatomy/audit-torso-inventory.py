# A declared torso/scapular/deep-spinal search universe; not every body muscle.
candidate_pattern = re.compile(r'pectoralis|serratus|intercostal muscle|external oblique|trapezius|rhomboid|'
    r'iliocostalis|longissimus|spinalis|diaphragm|subclavius|teres major|rotator|intertransversar|'
    r'levatores costarum|levator scapulae|linea alba|transversus thoracis')
rejected = []
for cid, row in parts.items():
    if cid in approved_ids or cid in nonterminal or not candidate_pattern.search(row['en']):
        continue
    name = row['en']
    if 'intercostal muscle' in name:
        reason = 'Un FMA por clase y dos FJ; no identifica espacios costales ni lateralidad por concepto. No se presentará cada FJ como un músculo intercostal individual.'
    elif any(x in name for x in ['cervic', 'capitis']):
        reason = 'Cuello/cabeza fuera del alcance de Fase 3B; se conservan sólo las subdivisiones torácicas/lumbares aprobadas.'
    elif 'diaphragm' in name:
        reason = 'Presente e identificable; aplazado por alcance: esta entrega se limita a paredes del torso y transición escapular.'
    elif 'linea alba' in name:
        reason = 'Estructura aponeurótica clasificada como unión anatómica, no un músculo; no se añade como unidad muscular.'
    elif 'levator scapulae' in name:
        reason = 'Identificable, aplazado para contener la extensión cervical; la transición escapular usa romboides y redondo mayor.'
    elif any(x in name for x in ['rotator', 'interspinalis', 'intertransversar', 'levatores costarum']):
        reason = 'Conjunto/representación segmentaria sin desglose vertebral o costal completo verificable; requiere una curación específica posterior.'
    else:
        reason = 'Identificable, aplazado para mantener un conjunto acotado; la espalda profunda ya incluye cuatro subdivisiones verificadas de erectores.'
    fids = bindings[cid]
    rejected.append(dict(sourceId=cid, representationId=row['representation id'], en=name,
        side=side_from_name(name), sourceType=isa_type(cid), elementIds=fids,
        reason=reason, archiveEntries={fid: directory[fid] for fid in fids}))
